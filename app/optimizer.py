def analyze_dockerfile(dockerfile_text: str) -> Dict[str, Any]:
    """
    Parses an unoptimized Dockerfile, identifies size and security antipatterns,
    and calculates baseline metrics.
    """
    lines = dockerfile_text.strip().splitlines()
    detected_issues = []
    estimated_base_size = 1020.0  # default full python image
    compiler_bloat = 0.0
    pip_cache_bloat = 0.0
    apt_cache_bloat = 0.0
    dev_deps_bloat = 0.0
    unignored_context_bloat = 48.0

    # 1. Base Image Inspection
    base_match = re.search(r"^FROM\s+([a-zA-Z0-9_\-\.:/]+)", dockerfile_text, re.MULTILINE | re.IGNORECASE)
    base_image = base_match.group(1) if base_match else "python:3.11"
    is_slim = "slim" in base_image.lower() or "alpine" in base_image.lower()

    if not is_slim:
        detected_issues.append({
            "rule": "BASE_IMAGE_BLOAT",
            "title": f"Heavy base image detected: '{base_image}' (~1,020 MB)",
            "recommendation": "Switch to a slim variant (e.g. 'python:3.11-slim-bookworm', ~140 MB).",
            "impact_mb": 880.0
        })
    else:
        estimated_base_size = 140.0

    # 2. Compilers in single stage
    has_compilers = bool(re.search(r"(build-essential|gcc|g\+\+|clang|make)", dockerfile_text, re.IGNORECASE))
    is_multistage = bool(re.search(r"FROM\s+.*?\s+AS\s+", dockerfile_text, re.IGNORECASE))

    if has_compilers and not is_multistage:
        compiler_bloat = 260.0
        detected_issues.append({
            "rule": "COMPILER_LEAKAGE",
            "title": "C/C++ Compilers and build headers installed in final runtime",
            "recommendation": "Use a multi-stage build: compile wheels in Builder, copy only wheels into Runtime.",
            "impact_mb": compiler_bloat
        })

    # 3. Apt cache cleanup
    has_apt = bool(re.search(r"apt-get\s+install", dockerfile_text, re.IGNORECASE))
    cleans_apt = bool(re.search(r"rm\s+-rf\s+/var/lib/apt/lists", dockerfile_text, re.IGNORECASE))

    if has_apt and not cleans_apt:
        apt_cache_bloat = 85.0
        detected_issues.append({
            "rule": "APT_CACHE_LEAKAGE",
            "title": "Apt package cache (/var/lib/apt/lists) retained in image layer",
            "recommendation": "Append '&& rm -rf /var/lib/apt/lists/*' in the same RUN layer.",
            "impact_mb": apt_cache_bloat
        })

    # 4. Pip cache check
    has_pip = bool(re.search(r"pip\s+install", dockerfile_text, re.IGNORECASE))
    has_no_cache = "--no-cache-dir" in dockerfile_text

    if has_pip and not has_no_cache:
        pip_cache_bloat = 75.0
        detected_issues.append({
            "rule": "PIP_CACHE_LEAKAGE",
            "title": "Pip download cache retained (~75-100 MB)",
            "recommendation": "Add '--no-cache-dir' to all pip install and pip wheel instructions.",
            "impact_mb": pip_cache_bloat
        })

    # 5. Dev dependencies check
    has_dev_deps = bool(re.search(r"requirements-dev\.txt|pytest|black|flake8|mypy", dockerfile_text, re.IGNORECASE))
    if has_dev_deps:
        dev_deps_bloat = 70.0
        detected_issues.append({
            "rule": "DEV_DEPENDENCIES_IN_PROD",
            "title": "Non-production dev/test packages included in production image",
            "recommendation": "Separate requirements.txt from requirements-dev.txt and install only production dependencies.",
            "impact_mb": dev_deps_bloat
        })

    # 6. Non-root user check
    has_non_root = bool(re.search(r"^USER\s+(?!root\b)[a-zA-Z0-9_\-]+", dockerfile_text, re.MULTILINE | re.IGNORECASE))
    if not has_non_root:
        detected_issues.append({
            "rule": "ROOT_PRIVILEGE_RISK",
            "title": "Container runs as privileged 'root' user (Security vulnerability)",
            "recommendation": "Add 'useradd -u 10001 -m appuser' and 'USER appuser'.",
            "impact_mb": 0.0
        })

    # 7. Healthcheck check
    has_healthcheck = bool(re.search(r"^HEALTHCHECK", dockerfile_text, re.MULTILINE | re.IGNORECASE))
    if not has_healthcheck:
        detected_issues.append({
            "rule": "MISSING_HEALTHCHECK",
            "title": "No native container HEALTHCHECK defined",
            "recommendation": "Add 'HEALTHCHECK --interval=30s CMD curl -f http://localhost:8000/health || exit 1'.",
            "impact_mb": 0.0
        })

    total_orig_mb = estimated_base_size + compiler_bloat + apt_cache_bloat + pip_cache_bloat + dev_deps_bloat + unignored_context_bloat
    total_opt_mb = 142.0
    saved_mb = max(0.0, total_orig_mb - total_opt_mb)
    reduction_pct = round((saved_mb / total_orig_mb) * 100, 1) if total_orig_mb > 0 else 0.0

    return {
        "original_base_image": base_image,
        "is_multistage": is_multistage,
        "detected_issues": detected_issues,
        "issue_count": len(detected_issues),
        "estimated_original_mb": round(total_orig_mb, 1),
        "estimated_optimized_mb": total_opt_mb,
        "saved_mb": round(saved_mb, 1),
        "reduction_percentage": reduction_pct,
        "layer_count_original": max(12, len([l for l in lines if l.strip().startswith(("RUN", "COPY", "ADD"))]) + 5),
        "layer_count_optimized": 7,
    }


def generate_optimized_dockerfile(original_dockerfile: str, python_version: str = "3.11") -> str:
    """
    Generates a production-grade 2-stage multi-stage Dockerfile based on best practices.
    """
    # Detect target port
    port_match = re.search(r"EXPOSE\s+(\d+)", original_dockerfile, re.IGNORECASE)
    port = port_match.group(1) if port_match else "8000"

    # Detect CMD
    cmd_match = re.search(r"CMD\s+(\[.*?\]|.+)", original_dockerfile, re.IGNORECASE)
    cmd = cmd_match.group(1) if cmd_match else '["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000"]'

    optimized_dockerfile = f"""# ==============================================================================
# OPTIMIZED PRODUCTION DOCKERFILE (MULTI-STAGE BUILD)
# Generated by Docker Image Optimizer
# ==============================================================================

# ------------------------------------------------------------------------------
# Stage 1: Build Environment (Builder)
# ------------------------------------------------------------------------------
FROM python:{python_version}-slim-bookworm AS builder

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

WORKDIR /build

# Install temporary build compilers needed for C-extensions (isolated to builder)
RUN apt-get update && apt-get install -y --no-install-recommends \\
    gcc \\
    libpq-dev \\
    && rm -rf /var/lib/apt/lists/*

# Copy only production requirements first to leverage Docker layer caching
COPY requirements.txt .

# Pre-compile wheels with pip cache disabled
RUN pip install --no-cache-dir --upgrade pip && \\
    pip wheel --no-cache-dir --no-deps --wheel-dir /build/wheels -r requirements.txt

# ------------------------------------------------------------------------------
# Stage 2: Final Lean Runtime
# ------------------------------------------------------------------------------
FROM python:{python_version}-slim-bookworm AS runtime

ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    PATH="/home/appuser/.local/bin:$PATH"

# Install only minimal runtime shared libraries (libpq5 for PostgreSQL, curl for healthcheck)
RUN apt-get update && apt-get install -y --no-install-recommends \\
    libpq5 \\
    curl \\
    && rm -rf /var/lib/apt/lists/*

# Create unprivileged non-root user
RUN groupadd -g 10001 appgroup && \\
    useradd -u 10001 -g appgroup -s /bin/bash -m appuser

WORKDIR /app

# Copy compiled wheels from builder and install with no pip cache
COPY --from=builder /build/wheels /wheels
RUN pip install --no-cache-dir /wheels/* && \\
    rm -rf /wheels

# Copy application source code with non-root ownership
COPY --chown=appuser:appgroup app /app/app

# Drop privileges to non-root user
USER appuser

# Healthcheck configuration
HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
    CMD curl -f http://localhost:{port}/health || exit 1

EXPOSE {port}

CMD {cmd}
"""
    return optimized_dockerfile

